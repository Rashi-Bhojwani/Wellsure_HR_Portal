import sys, json, struct, datetime
sys.path.insert(0, sys.argv[1])  # the downloaded pyzk-0.9 folder
from zk import base, const
from zk.base import ZK, make_commkey

zk = ZK('127.0.0.1', port=4370, ommit_ping=True)
out = {"source": "pyzk 0.9 (zk/base.py, zk/const.py), generated by running its own functions", "commkey": [], "headers": [], "time": [], "records40": [], "records16": []}

for key, session in [(0, 0), (0, 1234), (123456, 47153), (1, 1), (999999, 65535), (4294, 30000), (88888888, 500)]:
    try:
        k = make_commkey(key, session)
        out["commkey"].append({"key": key, "session": session, "ticks": 50, "bytes": k.hex()})
    except struct.error as e:
        out["commkey"].append({"key": key, "session": session, "ticks": 50, "error": str(e)})

cases = [
    (const.CMD_CONNECT, b'', 0, const.USHRT_MAX - 1),
    (const.CMD_AUTH, make_commkey(123456, 47153), 47153, 0),
    (const.CMD_GET_FREE_SIZES, b'', 47153, 1),
    (const.CMD_OPTIONS_RRQ, b'~SerialNumber\x00', 47153, 2),
    (1503, struct.pack('<bhii', 1, const.CMD_ATTLOG_RRQ, 0, 0), 47153, 3),
    (1504, struct.pack('<ii', 0, 0xFFc0), 47153, 4),
    (const.CMD_FREE_DATA, b'', 47153, 5),
    (const.CMD_GET_TIME, b'', 47153, 65534),
    (const.CMD_EXIT, b'', 12, 7),
    (const.CMD_GET_VERSION, b'odd', 9, 9),
]
for cmd, data, session, reply in cases:
    pkt = zk._ZK__create_header(cmd, data, session, reply)
    out["headers"].append({"command": cmd, "data": data.hex(), "session": session, "reply": reply, "packet": pkt.hex()})

for dt in [datetime.datetime(2021, 9, 1, 18, 30, 19), datetime.datetime(2026, 10, 9, 10, 2, 11), datetime.datetime(2000, 1, 1, 0, 0, 0), datetime.datetime(2099, 12, 31, 23, 59, 59), datetime.datetime(2024, 2, 29, 12, 0, 0)]:
    enc = zk._ZK__encode_time(dt)
    dec = zk._ZK__decode_time(struct.pack('<I', enc))
    out["time"].append({"local": dt.strftime('%Y-%m-%d %H:%M:%S'), "encoded": enc, "decoded": dec.strftime('%Y-%m-%d %H:%M:%S')})

# Records: built and decoded with the struct layouts in pyzk's get_attendance.
for uid, user_id, status, local, punch in [(1, "18", 15, datetime.datetime(2021, 9, 1, 18, 30, 19), 0), (7, "113", 1, datetime.datetime(2021, 9, 1, 19, 2, 25), 1), (300, "126", 255, datetime.datetime(2026, 10, 9, 10, 2, 11), 4)]:
    ts = struct.pack('<I', zk._ZK__encode_time(local))
    rec = struct.pack('<H24sB4sB8s', uid, user_id.encode(), status, ts, punch, b'\x00' * 8)
    u, uidb, st, t, p, sp = struct.unpack('<H24sB4sB8s', rec)
    out["records40"].append({"bytes": rec.hex(), "uid": u, "userId": uidb.split(b'\x00')[0].decode(), "status": st, "punch": p, "local": zk._ZK__decode_time(t).strftime('%Y-%m-%d %H:%M:%S')})
for user_id, local, status, punch, workcode in [(18, datetime.datetime(2021, 9, 1, 18, 30, 19), 1, 0, 1), (113, datetime.datetime(2021, 9, 1, 19, 2, 28), 15, 1, 0)]:
    ts = struct.pack('<I', zk._ZK__encode_time(local))
    rec = struct.pack('<I4sBB2sI', user_id, ts, status, punch, b'\x00\x00', workcode)
    a, t, st, p, r, w = struct.unpack('<I4sBB2sI', rec)
    out["records16"].append({"bytes": rec.hex(), "userId": str(a), "status": st, "punch": p, "workcode": w, "local": zk._ZK__decode_time(t).strftime('%Y-%m-%d %H:%M:%S')})

print(json.dumps(out, indent=2))
