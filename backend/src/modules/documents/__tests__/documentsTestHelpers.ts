import { randomUUID } from "node:crypto";
import request from "supertest";
import { minimalPdf } from "../../../lib/devFixtures";
import { prisma } from "../../../lib/prisma";
import { deleteWithDependents } from "../../../lib/__tests__/cleanup";
import { app } from "../../employee/__tests__/employeeTestHelpers";

export const pdf = (title = "Test document") => minimalPdf(title, ["Generated by a test."]);

export async function createTestCategory(appliesTo: "COMPANY" | "EMPLOYEE", opts: { isActive?: boolean } = {}) {
  const code = `TEST_${randomUUID().slice(0, 8).toUpperCase()}`;
  return prisma.documentCategory.create({ data: { code, name: `Test ${code}`, appliesTo, isActive: opts.isActive ?? true } });
}

// Deletes the categories and — through the schema-driven engine — every
// document filed under them, their download records and their stored files.
export async function cleanupTestCategories(ids: string[]): Promise<void> {
  await deleteWithDependents("DocumentCategory", ids);
}

// Adds a literal role code to an existing fixture user. resolveDataScope
// matches literal codes, so ALL scope needs e.g. "HR_ADMIN" itself.
export async function addLiteralRole(userId: string, code: string): Promise<void> {
  const role = await prisma.role.upsert({ where: { code }, create: { code, name: code }, update: {} });
  await prisma.userRole.create({ data: { userId, roleId: role.id } });
}

// Follows a signed download URL the way a browser would, through the local
// storage driver's /dev/storage route.
export async function fetchSignedUrl(url: string) {
  const u = new URL(url);
  return request(app).get(`${u.pathname}${u.search}`).buffer(true).parse((res, cb) => {
    const chunks: Buffer[] = [];
    res.on("data", (c: Buffer) => chunks.push(c));
    res.on("end", () => cb(null, Buffer.concat(chunks)));
  });
}
