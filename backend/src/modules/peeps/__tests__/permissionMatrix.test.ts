import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import request from "supertest";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { purgeAppendOnly } from "../../../lib/__tests__/cleanup";
import { prisma } from "../../../lib/prisma";
import { app, authHeader, cleanupEmployeeTestOrgMasters, cleanupFullTestEmployee, createEmployeeTestOrgMasters, type TestOrgMasters } from "../../employee/__tests__/employeeTestHelpers";
import { EXPECTED } from "./permissionMatrix.expected";
import { ACTORS, concretePath, makeActors, peepsRoutes, PROBE_BODIES, type People } from "./permissionMatrix.shared";
import { clearPeepsSettings } from "./peepsTestKit";

// Peeps Stage 4, phase 1: the permission matrix. Every Peeps route the API serves is called as each of ten actors: signed out, an employee,
// the employee's manager, an unrelated manager, HR (HR Admin), a Wellsure Office member holding every capability (audiences left Not set),
// a non-member employee, a director, the Developer and a former employee (deactivated account). Every :param is an id that does not exist,
// so nothing is changed; bodies are {} unless a valid probe body is needed to reach a service-level refusal.
//
// The expected status of every call is in permissionMatrix.expected.ts, reviewed route by route against the owner decisions (the review
// is recorded in docs/plans/PEEPS_STAGE_REPORTS.md, Stage 4). The test fails when a route has no row, when a row names a route that no
// longer exists, and when any status differs. 401/403 mean the gate refused; any other status means the gate let the call through and the
// service decided (record-level refusals of real records are proven in each module's own tests and in the confidentiality scan).
// To regenerate after an intended change: PERMISSION_MATRIX_WRITE=1 npx vitest run this file, then review the diff before committing.

describe("Peeps permission matrix: every route × ten actors", () => {
  let org: TestOrgMasters;
  let people: People;
  let tokens: Record<string, string>;
  const routes = peepsRoutes(readFileSync(path.resolve(__dirname, "../../managers/__tests__/routeInventory.ts"), "utf8"));

  beforeAll(async () => {
    org = await createEmployeeTestOrgMasters();
    const r = await makeActors(org);
    people = r.people;
    tokens = r.tokens as Record<string, string>;
  });

  afterAll(async () => {
    const ids = Object.values(people).map((x) => x.employeeId);
    const changes = (await prisma.officeMembershipChange.findMany({ where: { employeeId: { in: ids } }, select: { id: true } })).map((c) => c.id);
    await purgeAppendOnly("AuditLog", { entityId: { in: changes } });
    await clearPeepsSettings();
    for (const x of Object.values(people)) await cleanupFullTestEmployee(x.employeeId);
    await cleanupEmployeeTestOrgMasters(org);
  });

  it("every Peeps route has a row, and every row is a real Peeps route", () => {
    expect(routes.length).toBeGreaterThan(150);
    expect(routes.filter((r) => !EXPECTED[r]), "routes with no row in permissionMatrix.expected.ts").toEqual([]);
    expect(Object.keys(EXPECTED).filter((r) => !routes.includes(r)), "rows for routes that no longer exist").toEqual([]);
  });

  it("every route answers each actor exactly as reviewed", async () => {
    const actual: Record<string, string> = {};
    for (const id of routes) {
      const [method, route] = id.split(" ") as [string, string];
      const statuses: number[] = [];
      for (const a of ACTORS) {
        let req = (request(app) as unknown as Record<string, (u: string) => request.Test>)[method.toLowerCase()]!(concretePath(route));
        if (a !== "anon") req = req.set(...authHeader(tokens[a]!));
        const res = method === "GET" ? await req : await req.send(PROBE_BODIES[id] ?? {});
        statuses.push(res.status);
      }
      actual[id] = statuses.join(" ");
    }
    if (process.env.PERMISSION_MATRIX_WRITE === "1") {
      const body = Object.entries(actual).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
      writeFileSync(path.resolve(__dirname, "permissionMatrix.expected.ts"), `// Reviewed expected statuses, actors in this order: ${ACTORS.join(", ")}.\n// Generated by permissionMatrix.test.ts (PERMISSION_MATRIX_WRITE=1) and reviewed; see the Stage 4 report.\nexport const EXPECTED: Record<string, string> = {\n${body}\n};\n`);
    }
    const wrong = Object.entries(actual).filter(([id, v]) => EXPECTED[id] !== v).map(([id, v]) => `${id}: expected [${EXPECTED[id]}] got [${v}]`);
    expect(wrong).toEqual([]);
    // The two rules that hold for every route: signed out and a former employee never get through (the public joiner link aside).
    for (const [id, v] of Object.entries(actual)) {
      const s = v.split(" ").map(Number);
      if (id.startsWith("GET /api/joining/") || id.startsWith("POST /api/joining/")) continue;
      expect(s[0], `${id} signed out`).toBe(401);
      expect(s[9], `${id} former employee`).toBe(401);
    }
  }, 600_000);
});
