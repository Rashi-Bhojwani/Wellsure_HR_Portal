// The endpoint audit for manager reach (Phase 5 commit E2,
// docs/plans/PHASE_5.md §E2 "Endpoint audit"). Every route the API serves
// is classified here; routeInventory.test.ts fails on any route that isn't,
// on any entry that no longer exists, and on any classification the real
// route gates (read from requirePermission/requireAnyPermission) contradict.
//
//   public    — no sign-in (login, invitations, password reset).
//   self      — only ever the caller's own data.
//   everyone  — available to every signed-in employee by design and not
//               personal data of others beyond the directory's configured
//               fields (catalogs, the directory, the Engage feed). Never
//               gated on a manager-grantable key.
//   scoped    — another person's data, narrowed to the caller's data scope
//               in the service layer. Those reachable with a
//               manager-grantable key have an IDOR case in
//               managerReach.test.ts (team member: allowed; outsider: never).
//   admin     — gated on keys a manager can never hold (non-grantable), or
//               Super-Admin-only in the service.
//
// A new endpoint fails the test until it's added here, with a reason.

export type RouteKind = "public" | "self" | "everyone" | "scoped" | "admin";
export interface RouteClass {
  kind: RouteKind;
  why?: string;
}

