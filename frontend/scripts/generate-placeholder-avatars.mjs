const people = [];
for (let i = 0; i < 24; i += 1) {
  const skin = skins[i % skins.length];
  const hair = hairColours[(i * 5) % hairColours.length];
  const style = hairStyles[(i * 7) % hairStyles.length];
  const bg = backgrounds[i % backgrounds.length];
  const shirt = ["#4F7CAC", "#3E8E7E", "#C2654E", "#8E6BB8", "#C99A2E", "#5C6B7A"][(i * 3) % 6];
  const glasses = i % 5 === 2 ? `<g fill="none" stroke="#2B2B2B" stroke-width="1.6"><circle cx="41" cy="46" r="4.5"/><circle cx="55" cy="46" r="4.5"/><path d="M45.5 46h5"/></g>` : "";
  const body =
    `<path d="M20 92c2-16 13-24 28-24s26 8 28 24z" fill="${shirt}"/>` +
    `<rect x="43" y="58" width="10" height="12" rx="4" fill="${skin}"/>` +
    `<ellipse cx="48" cy="45" rx="17" ry="19" fill="${skin}"/>` +
    style(hair) +
    `<circle cx="41" cy="46" r="1.8" fill="#2B2B2B"/><circle cx="55" cy="46" r="1.8" fill="#2B2B2B"/>` +
    glasses +
    `<path d="M42 54c3 3 9 3 12 0" fill="none" stroke="#7A3B2E" stroke-width="1.8" stroke-linecap="round"/>`;
  const id = `person-${String(i + 1).padStart(2, "0")}`;
  people.push({ id, name: `Person ${i + 1}`, file: `characters/${id}.svg` });
  writeFileSync(path.join(out, "characters", `${id}.svg`), svg(`Person ${i + 1}`, body, bg));
}

