// Ant Design 6 ConfigProvider theme for each mode, from tokens.ts (docs/DESIGN_SYSTEM.md §1–3, §6). The global colorPrimary is the board's green accent (checkboxes,
// radios, switches, selection); the primary BUTTON is the board's navy (white in dark), set on the Button component only.
